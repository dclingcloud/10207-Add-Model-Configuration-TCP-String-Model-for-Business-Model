export function generateSummaryFromRules(rules: ParameterRule[]): string {
  if (!rules || rules.length === 0) return '-';
  const parts = rules.filter(r => r.enabled).map(r => {
    if (r.ruleMode === 'offset') {
      return `偏移量:${r.offset || 0};长度:${r.length || 0}`;
    }
    const chunks = [];
    if (r.startValue) chunks.push(`${r.startPrefixType}:${r.startValue}`);
    if (r.connector) chunks.push(`连接符:${r.connector}`);
    if (r.endValue) chunks.push(`${r.endSuffixType}:${r.endValue}`);
    return chunks.join(';') || `${r.fieldCategory}`;
  });
  return parts.slice(0, 4).join(';;') + (parts.length > 4 ? ';...' : '');
}
